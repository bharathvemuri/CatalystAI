"""`harness setup-project` — phase 2, setup.

Projects the validated task graph onto an issue tracker: one issue per task
file, the task's ``dir`` as a label, its ``phase`` as a milestone (spec section
4). Deliberately creates no folders in the target project — open question #9
settled that target directories come into existence in phase 3, when the
Developer agent first implements in one.

Three properties shape the code more than the API calls do:

*Approval before outward effect.* Issues are public, numbered, and awkward to
un-create, so the command prints a complete plan and stops for a yes. ``--yes``
exists for CI; ``--dry-run`` stops before the question.

*Re-runnable.* The command is expected to run again after the task files change.
A task already linked to an issue is never re-created; its issue is compared
against the task file and updated only where the two disagree. Labels a human
added by hand are kept — the harness adds, it does not prune.

*Failure is partial by default.* A rejected credential or an exhausted rate
limit dooms every remaining task, so the run aborts on it. One malformed issue
does not, so the other thirty-nine proceed and the failures are reported
together at the end. Either way every issue that *was* created is already in the
event log, so the next run resumes rather than duplicating.
"""

